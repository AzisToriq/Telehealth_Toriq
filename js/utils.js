  function icon(name) { return ICONS[name] || ''; }

  function hydrateStaticIcons() {
    document.querySelectorAll('[data-icon]').forEach((el) => {
      const key = el.getAttribute('data-icon');
      if (ICONS[key]) el.innerHTML = ICONS[key];
    });
  }

  function escapeHtml(str) {
    if (str === null || str === undefined) return '';
    return String(str)
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;')
      .replace(/'/g, '&#39;');
  }

  function formatDateTime(iso) {
    if (!iso) return '—';
    try {
      const d = new Date(iso);
      if (Number.isNaN(d.getTime())) return String(iso);
      return new Intl.DateTimeFormat('id-ID', {
        day: '2-digit', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit'
      }).format(d);
    } catch { return String(iso); }
  }

  function formatShortDate(iso) {
    if (!iso) return '—';
    try {
      const d = new Date(iso);
      if (Number.isNaN(d.getTime())) return String(iso);
      return new Intl.DateTimeFormat('id-ID', { day: '2-digit', month: 'short' }).format(d);
    } catch { return String(iso); }
  }

  function todayIsoDate() {
    const now = new Date();
    return `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}-${String(now.getDate()).padStart(2, '0')}`;
  }

  function isValueFilled(v) {
    return v !== undefined && v !== null && v !== '' && !(Array.isArray(v) && v.length === 0);
  }

  function isVisible(cond, answers) {
    if (!cond) return true;
    const ans = answers || {};
    if (Array.isArray(cond.any)) return cond.any.some((c) => isVisible(c, ans));
    if (Array.isArray(cond.all)) return cond.all.every((c) => isVisible(c, ans));
    const v = ans[cond.question];
    const filled = isValueFilled(v);
    if ('equals' in cond) return v === cond.equals;
    if ('in' in cond) return Array.isArray(cond.in) && cond.in.includes(v);
    if ('includes' in cond) return Array.isArray(v) && v.includes(cond.includes);
    if ('filled' in cond) return filled === Boolean(cond.filled);
    return true;
  }

  function getDeliveryBadge(statusObj) {
    const kode = typeof statusObj === 'string' ? statusObj : statusObj?.kode || 'draft';
    const label = typeof statusObj === 'string'
      ? (kode === 'terkirim' ? 'Terkirim' : 'Draf (belum dikirim)')
      : statusObj?.label || kode;
    return `<span class="badge ${kode === 'terkirim' ? 'badge-success' : 'badge-neutral'}">${escapeHtml(label)}</span>`;
  }

  function getReviewBadge(statusObj) {
    const kode = typeof statusObj === 'string' ? statusObj : statusObj?.kode || 'belum_dikirim';
    const label = typeof statusObj === 'string' ? kode.replace(/_/g, ' ') : statusObj?.label || kode;
    const map = {
      belum_dikirim: 'badge-neutral',
      menunggu_peninjauan: 'badge-info',
      sedang_ditinjau: 'badge-indigo',
      perlu_klarifikasi: 'badge-warning',
      klarifikasi_dijawab: 'badge-primary',
      sudah_ditinjau: 'badge-success'
    };
    return `<span class="badge ${map[kode] || 'badge-neutral'}">${escapeHtml(label)}</span>`;
  }

  function getGradingBadge(statusObj) {
    const kode = typeof statusObj === 'string' ? statusObj : statusObj?.kode || 'belum_diperiksa';
    const label = typeof statusObj === 'string' ? kode.replace(/_/g, ' ') : statusObj?.label || kode;
    const map = {
      disetujui: 'badge-success',
      perlu_revisi: 'badge-warning',
      ditolak: 'badge-danger',
      belum_diperiksa: 'badge-neutral'
    };
    return `<span class="badge ${map[kode] || 'badge-neutral'}">${escapeHtml(label)}</span>`;
  }

  function getScoreCategoryClass(kode) {
    const k = String(kode || '').toLowerCase();
    if (k.includes('minimal')) return 'badge-success';
    if (k.includes('ringan')) return 'badge-info';
    if (k.includes('sedang')) return 'badge-warning';
    if (k.includes('berat')) return 'badge-danger';
    return 'badge-primary';
  }

  function getInitials(name) {
    if (!name) return 'AT';
    const parts = name.trim().split(/\s+/);
    return ((parts[0]?.[0] || '') + (parts[1]?.[0] || '')).toUpperCase() || 'AT';
  }

  function downloadFile(filename, content, mime = 'application/json') {
    const blob = new Blob([content], { type: mime });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    a.remove();
    setTimeout(() => URL.revokeObjectURL(url), 1000);
  }

  function downloadConsultationIcs({ assessmentId, dateIso, description, reviewer }) {
    const dt = new Date(dateIso);
    if (Number.isNaN(dt.getTime())) return false;
    const pad = (n) => String(n).padStart(2, '0');
    const toIcs = (d) => `${d.getUTCFullYear()}${pad(d.getUTCMonth() + 1)}${pad(d.getUTCDate())}T${pad(d.getUTCHours())}${pad(d.getUTCMinutes())}00Z`;
    const end = new Date(dt.getTime() + 30 * 60000);
    const ics = [
      'BEGIN:VCALENDAR',
      'VERSION:2.0',
      'PRODID:-//PulseCare Telehealth//ID',
      'BEGIN:VEVENT',
      `UID:${assessmentId}@pulsecare-telehealth`,
      `DTSTAMP:${toIcs(new Date())}`,
      `DTSTART:${toIcs(dt)}`,
      `DTEND:${toIcs(end)}`,
      `SUMMARY:Konsultasi Telehealth (${assessmentId})`,
      `DESCRIPTION:${(description || 'Jadwal konsultasi tindak lanjut').replace(/\n/g, '\\n')} - Petugas: ${reviewer || 'Tenaga Kesehatan'}`,
      'END:VEVENT',
      'END:VCALENDAR'
    ].join('\r\n');
    downloadFile(`konsultasi-${assessmentId}.ics`, ics, 'text/calendar;charset=utf-8');
    return true;
  }

